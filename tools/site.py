#!/usr/bin/env python3
"""Builds the generated parts of the project site and the READMEs. Run from the repository root after
changing ui/ or tools/texts.py:

    python3 tools/site.py

  docs/i18n.js            site texts in 12 languages (tools/texts.py + the app's own tutorial texts)
  docs/demo/              the live preview: ui/index.html + docs/demo/sim.js (made-up data)
  README.md               English README
  docs/readme/README.*.md the other languages
"""
import json
import os
import re
import shutil
import sys

sys.path.insert(0, os.path.dirname(__file__))
import texts  # noqa: E402

REPO = "Yasaiek/Orbek-Discord-Quests-Orbs"
SITE = "https://yasaiek.github.io/Orbek-Discord-Quests-Orbs/"
LANGS = [("en", "English"), ("pl", "Polski"), ("de", "Deutsch"), ("fr", "Français"), ("es", "Español"), ("it", "Italiano"),
         ("pt_BR", "Português (BR)"), ("ru", "Русский"), ("uk", "Українська"), ("tr", "Türkçe"), ("ja", "日本語"), ("zh_CN", "简体中文")]
FLAG = lambda c: c.split("_")[0]  # docs/flags/<flag>.svg
version = re.search(r'var version = "([0-9.]+)"', open("engine.go", encoding="utf-8").read()).group(1)


def app_lang(code):
    return json.load(open("ui/lang/%s.json" % code, encoding="utf-8"))


def tutorial(code):
    d = app_lang(code)
    return [[d["guide.%dt" % i], d["guide.%d" % i]] for i in range(1, 9)]


# ---- docs/i18n.js ----
site = {}
for code, _ in LANGS:
    d = dict(zip(texts.KEYS, texts.T[code]))
    d["tut"] = tutorial(code)
    site[code] = d
with open("docs/i18n.js", "w", encoding="utf-8", newline="\n") as fh:
    fh.write("// Generated by tools/site.py from tools/texts.py and ui/lang. Do not edit by hand.\n")
    fh.write("const SITE_LANGS = %s;\n" % json.dumps(dict(LANGS), ensure_ascii=False))
    fh.write("const SITE = %s;\n" % json.dumps(site, ensure_ascii=False, indent=1))

# ---- docs/demo ----
src = open("ui/index.html", encoding="utf-8").read()
assert src.count("<script>") == 1, "expected exactly one inline script in ui/index.html"
inject = '<script>window.ORBEK_VERSION = "%s";</script>\n<script src="sim.js"></script>\n<script>' % version
out = src.replace("<script>", inject, 1).replace("__KEY__", "demo")
os.makedirs("docs/demo", exist_ok=True)
with open("docs/demo/index.html", "w", encoding="utf-8", newline="\n") as fh:
    fh.write("<!-- Generated by tools/site.py from ui/index.html. Do not edit. -->\n" + out)
shutil.copyfile("ui/icon.svg", "docs/demo/icon.svg")
shutil.rmtree("docs/demo/lang", ignore_errors=True)
shutil.copytree("ui/lang", "docs/demo/lang")

# ---- READMEs ----
def readme(code, root):
    d = dict(zip(texts.KEYS, texts.T[code]))
    up = "" if root else "../../"
    me = lambda c: (up + "README.md") if c == "en" else (up + "docs/readme/README.%s.md" % FLAG(c))
    flags = " ".join('<a href="%s" title="%s"><img src="%sdocs/flags/%s.svg" width="24" alt="%s"></a>' % (me(c), n, up, FLAG(c), n) for c, n in LANGS)
    feats = "\n".join("- **%s** – %s" % (d["f%dt" % i], d["f%d" % i]) for i in range(1, 7))
    tut = "\n".join("%d. **%s** – %s" % (i + 1, h, p) for i, (h, p) in enumerate(tutorial(code)))
    faq = "\n\n".join("**%s**  \n%s" % (d["q%d" % i], d["a%d" % i]) for i in range(1, 5))
    return f"""<p align="center"><img src="{up}docs/img/icon.png" width="104" alt=""></p>
<h1 align="center">Orbek – Discord Quests &amp; Orbs</h1>
<p align="center">{d["lead"]}</p>
<p align="center">{flags}</p>
<p align="center">
  <a href="https://github.com/{REPO}/releases/latest/download/Orbek.exe"><b>⬇ {d["dl"]}</b></a> &nbsp;·&nbsp;
  <a href="{SITE}"><b>🌐 {d["website"]}</b></a> &nbsp;·&nbsp;
  <a href="{up}CHANGELOG.md">{d["changelog"]}</a> &nbsp;·&nbsp;
  <a href="https://github.com/{REPO}/issues/new">{d["bug"]}</a>
</p>
<p align="center"><img src="{up}docs/img/panel.png" alt="Orbek" width="880"></p>

## {d["whatT"]}

{feats}

## {d["tutT"]}

{tut}

## {d["faqT"]}

{faq}

## {d["buildT"]}

{d["build1"]}

```
go build -trimpath -ldflags "-H=windowsgui -s -w" -o Orbek.exe .
```

## {d["disclaimerT"]}

{d["disclaimer"]}
"""


os.makedirs("docs/readme", exist_ok=True)
for code, _ in LANGS:
    path = "README.md" if code == "en" else "docs/readme/README.%s.md" % FLAG(code)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(readme(code, code == "en"))
print("site, demo and READMEs built (version %s)" % version)
