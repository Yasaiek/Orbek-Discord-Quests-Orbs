package main

import (
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
)

// findBrowser looks for a Chromium-based browser already installed on the computer (Edge first: every Windows has it).
func findBrowser() string {
	if p := os.Getenv("ORBEK_BROWSER"); p != "" {
		return p
	}
	var cands []string
	if runtime.GOOS == "windows" {
		roots := []string{os.Getenv("ProgramFiles(x86)"), os.Getenv("ProgramFiles"), os.Getenv("LocalAppData")}
		for _, rel := range []string{`Microsoft\Edge\Application\msedge.exe`, `Google\Chrome\Application\chrome.exe`, `BraveSoftware\Brave-Browser\Application\brave.exe`} {
			for _, r := range roots {
				if r != "" {
					cands = append(cands, filepath.Join(r, rel))
				}
			}
		}
	} else {
		for _, n := range []string{"microsoft-edge", "google-chrome", "chromium", "chromium-browser"} {
			if p, err := exec.LookPath(n); err == nil {
				cands = append(cands, p)
			}
		}
	}
	for _, c := range cands {
		if st, err := os.Stat(c); err == nil && !st.IsDir() {
			return c
		}
	}
	return ""
}

func extraFlags() []string {
	if f := os.Getenv("ORBEK_BROWSER_FLAGS"); f != "" {
		return strings.Fields(f)
	}
	return nil
}

// panelTheme is the seed colour ("r,g,b") of the browser theme used for the panel window.
const panelTheme = "139,108,255"

// openPanel shows the control panel as a chromeless app window; the window is a separate browser profile
// that exists only while the panel is open.
func openPanel(url, dataDir string) error {
	exe := findBrowser()
	if exe == "" {
		if runtime.GOOS == "windows" {
			return exec.Command("rundll32", "url.dll,FileProtocolHandler", url).Start()
		}
		return exec.Command("xdg-open", url).Start()
	}
	args := []string{
		"--app=" + url,
		"--user-data-dir=" + filepath.Join(dataDir, "panel-profile"),
		"--window-size=1180,820",
		"--no-first-run", "--no-default-browser-check", "--disable-sync",
		"--disable-background-networking", "--disable-extensions",
		// The title bar of an app window is drawn by the browser and takes the colours of the browser's
		// theme (a page's theme-color is ignored there). The panel has its own profile, so give that
		// profile a dark theme in the app's own blue instead of the browser's default grey.
		"--install-autogenerated-theme=" + panelTheme,
	}
	args = append(args, extraFlags()...)
	cmd := exec.Command(exe, args...)
	if err := cmd.Start(); err != nil {
		return err
	}
	go cmd.Wait()
	return nil
}

// openMini opens the small always-at-hand window (a profile of its own, so it lives next to the panel).
func openMini(url, dataDir string) error {
	exe := findBrowser()
	if exe == "" {
		return openURL(url)
	}
	args := []string{"--app=" + url, "--user-data-dir=" + filepath.Join(dataDir, "mini-profile"), "--window-size=380,620",
		"--no-first-run", "--no-default-browser-check", "--disable-sync", "--disable-background-networking", "--disable-extensions",
		"--install-autogenerated-theme=" + panelTheme}
	cmd := exec.Command(exe, append(args, extraFlags()...)...)
	if err := cmd.Start(); err != nil {
		return err
	}
	go cmd.Wait()
	return nil
}

// openURL opens an address in the user's default browser.
func openURL(u string) error {
	if runtime.GOOS == "windows" {
		return exec.Command("rundll32", "url.dll,FileProtocolHandler", u).Start()
	}
	if os.Getenv("ORBEK_NO_WINDOW") != "" {
		return nil
	}
	return exec.Command("xdg-open", u).Start()
}
